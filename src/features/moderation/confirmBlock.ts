import { confirm } from '@/components/ConfirmDialog';

/**
 * Подтверждение блокировки — с тем, что изменится. Обещает только то, что
 * делает сервер: переписка публична, и прочитать общие чаты по-прежнему можно.
 */
export function confirmBlock(name: string): Promise<boolean> {
  return confirm({
    title: `Заблокировать ${name}?`,
    message:
      'Вы больше не сможете писать друг другу и звонить, звать в группы и в друзья. Дружба и заявки пропадут. Этот человек не найдёт вас в поиске, не откроет ваш профиль и не сможет комментировать и реагировать на ваши сообщения, а его комментарии и реакции пропадут у вас. Общие чаты останутся читаемыми. О блокировке ему не сообщат.',
    confirmLabel: 'Заблокировать',
    cancelLabel: 'Отмена',
    destructive: true,
  });
}
