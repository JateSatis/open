/** Цвет кластера по эмодзи-лидеру; `other` — любая эмодзи вне таблицы. */
export type ClusterTones = Readonly<Record<string, string>> & { readonly other: string };

type Surface = {
  tones: ClusterTones;
  /** Альфа заливки: при одной реакции — `fill[0]`, к потолку — `fill[1]`. */
  fill: readonly [number, number];
  /** Альфа силуэтов поверх заливки — тот же тон, плотнее её. */
  pattern: readonly [number, number];
};

