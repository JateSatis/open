/**
 * Чата нет: удалён (личный диалог удаляют для всех) или не существовал.
 * Удалённый база не отдаёт вовсе, поэтому одно от другого не отличить — и
 * не нужно: показать в нём нечего. Отдельный модуль: тесты подменяют
 * `chats.ts` целиком, а класс для `instanceof` должен остаться настоящим.
 */
export class ChatGoneError extends Error {
  constructor(readonly chatId: string) {
    super('Чат удалён');
    this.name = 'ChatGoneError';
  }
}
