-- Один файл — фото одной группы.
--
-- Сменив или убрав фото, клиент удаляет прежний файл, если тот лежит в его
-- префиксе. Это безопасно, только пока файл не стоит у другой группы: иначе
-- удаление оставило бы ту группу с битой ссылкой. Приложение на каждую смену
-- загружает новый файл, но `set_chat_avatar` можно вызвать в обход него с
-- адресом, уже стоящим у другой моей группы, — поэтому это инвариант схемы.

create unique index chats_avatar_url_key
  on public.chats (avatar_url) where avatar_url is not null;
